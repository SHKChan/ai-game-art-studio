class ExternalAssetProvider(Provider):
    """Engine C: artwork produced elsewhere (any tool, any service). Always available."""
    id = "external"
    name = "External assets (import)"
    kind = "import"

    def __init__(self, ffmpeg: str | None):
        self.ffmpeg = ffmpeg

    def status(self) -> ProviderStatus:
        return ProviderStatus(True, "", {"ffmpeg": bool(self.ffmpeg), "video_import": bool(self.ffmpeg)})

    def capabilities(self) -> dict:
        return {"formats": ["png", "png-sequence", "sprite-sheet", "gif", "apng", "webp"] + (["mp4", "webm", "mov"] if self.ffmpeg else []),
                "video": bool(self.ffmpeg)}

    def generate(self, req: GenerationRequest, ctx: JobContext) -> GenerationResult:
        paths = [Path(p) for p in req.params.get("files", [])]
        if not paths:
            raise GenerationError("No files to import", "bad_request")
        out = Path(req.out_dir)
        out.mkdir(parents=True, exist_ok=True)
        res = []
        for i, p in enumerate(paths):
            dst = out / f"import_{i:03d}{p.suffix.lower()}"
            shutil.copyfile(p, dst)
            res.append(dst)
        return GenerationResult(res, {"provider": "external", "files": [p.name for p in paths]})


FIXTURE_NOTE = "TEST FIXTURE — copied from the bundled knight sample art; NOT generated by an AI model in this run."


class MockGenerationProvider(Provider):
    """Deterministic offline provider for tests and demos. It returns *existing* genuine artwork
    (the bundled knight sample) and labels every result
    as a test fixture. It never fabricates 'AI' output."""
    id = "mock"
    name = "Mock generation (test fixtures)"
    kind = "test_fixture"

    FIXTURES = {
        "knight_idle": APP_ROOT / "samples" / "knight" / "idle" / "atlas.png",
        "knight_run": APP_ROOT / "samples" / "knight" / "run" / "atlas.png",
        "knight_light": APP_ROOT / "samples" / "knight" / "light" / "atlas.png",
        "knight_poster": APP_ROOT / "samples" / "knight" / "idle" / "poster.png",
    }

    def __init__(self, delay_s: float = 0.0, fail_mode: str | None = None):
        self.delay_s, self.fail_mode = delay_s, fail_mode

    def status(self) -> ProviderStatus:
        missing = [k for k, p in self.FIXTURES.items() if not p.exists()]
        if missing:
            return ProviderStatus(False, f"Fixture files missing: {missing}")
        return ProviderStatus(True, "", {"note": FIXTURE_NOTE})

    def capabilities(self) -> dict:
        return {"fixtures": list(self.FIXTURES), "kinds": ["text_to_image", "image_to_image", "pose_keyframe", "sheet"]}

    def generate(self, req: GenerationRequest, ctx: JobContext) -> GenerationResult:
        if self.fail_mode == "fail":
            raise GenerationError("Mock provider configured to fail", "execution_error")
        steps = 5
        for i in range(steps):
            ctx.check_cancel()
            time.sleep(self.delay_s / steps)
            ctx.progress((i + 1) / steps, f"mock step {i + 1}/{steps}")
        if self.fail_mode == "timeout":
            raise GenerationError("Mock provider simulated timeout", "timeout", retryable=True)
        key = req.params.get("fixture") or {"pose_keyframe": "knight_light", "sheet": "knight_run", "action_strip": "knight_run"}.get(req.kind, "knight_poster")
        src = self.FIXTURES.get(key)
        if not src or not src.exists():
            raise GenerationError(f"Unknown fixture {key}", "bad_request")
        out = Path(req.out_dir)
        out.mkdir(parents=True, exist_ok=True)
        dst = out / f"fixture_{key}.png"
        shutil.copyfile(src, dst)
        return GenerationResult([dst], {"provider": "mock", "fixture": key, "source": src.relative_to(APP_ROOT).as_posix(),
                                        "is_test_fixture": True, "warning": FIXTURE_NOTE, "prompt": req.prompt}, is_test_fixture=True)


class CodexImageProvider(Provider):
    """Codex image generation through the native app-server bridge (artstudio.providers.codex_rpc, from Pixel Atelier).
    Requires a logged-in `codex` CLI with built-in image generation (no API keys). Optional provider."""
    id = "codex"
    name = "Codex CLI (image generation)"
    kind = "image_generation"
    counts_toward_budget = True

    def __init__(self, codex_bin: str = "", timeout: int = 300):
        self.codex_bin, self.timeout = codex_bin, timeout

    def status(self) -> ProviderStatus:
        from ..codex_cli import resolve
        cmd = resolve(self.codex_bin)
        if not cmd:
            return ProviderStatus(False, "codex CLI not found (install it and run `codex login`, or set codex_bin)")
        return ProviderStatus(True, "codex CLI found; login is checked at the first call", {"command": cmd[0], "verified": False})

    def capabilities(self) -> dict:
        return {"kinds": ["sheet", "pose_keyframe", "master_candidate"], "prompt_writing": True, "reference_images": True}

    def generate(self, req: GenerationRequest, ctx: JobContext) -> GenerationResult:
        st = self.status()
        if not st.available:
            raise GenerationError(st.reason, "provider_unavailable")
        from ..codex_cli import app_server_command
        from .codex_rpc import BridgeError, CodexClient
        events: list = []

        def on_event(e):
            events.append(e)
            if e.get("type") == "imageGeneration":
                ctx.progress(0.5, f"codex image {e.get('status')}")

        ctx.progress(0.05, "starting codex")
        try:
            client = CodexClient(on_event, command=app_server_command(self.codex_bin))
        except (OSError, BridgeError) as e:
            raise GenerationError(f"Codex could not start: {e}", "provider_unavailable") from e
        try:
            ref = Path(req.reference_images[0]) if req.reference_images else None
            res = client.generate(ref, req.prompt, Path(req.out_dir), timeout=int(req.params.get("timeout", self.timeout)))
        except BridgeError as e:
            raise GenerationError(f"Codex generation failed: {e}", "execution_error", {"events": events[-10:]}, retryable=False) from e
        finally:
            client.close()
        return GenerationResult([Path(p) for p in res["images"]], {"provider": "codex", "model": res.get("model"),
                                                                    "thread_id": res.get("thread_id"), "events": events[-20:]})


def mark_fixture(image_path: Path) -> None:
    """Embed a provenance text chunk in fixture PNGs (visible to any PNG inspector)."""
    with Image.open(image_path) as im:
        from PIL import PngImagePlugin
        info = PngImagePlugin.PngInfo()
        info.add_text("artstudio:provenance", FIXTURE_NOTE)
        im.save(image_path, pnginfo=info)
